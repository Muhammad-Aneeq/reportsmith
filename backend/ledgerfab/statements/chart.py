LINES_BY_CODE: dict[str, StatementLineDef] = {ln.code: ln for ln in STATEMENT_LINES}
LINE_ORDER: dict[str, int] = {ln.code: i for i, ln in enumerate(STATEMENT_LINES)}


def lines_for(statement: str) -> tuple[StatementLineDef, ...]:
    return tuple(ln for ln in STATEMENT_LINES if ln.statement == statement)


def cash_flow_section(code: str) -> str:
    """Which cash-flow section a movement against this account belongs to."""
    return ACCOUNTS_BY_CODE[code].cf_section
