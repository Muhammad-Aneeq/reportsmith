MAGNITUDE = "magnitude"
SIGNED = "signed"


@dataclass(frozen=True, slots=True)
class StatementLineDef:
    """One line of one statement, and everything the rest of the system needs to know
    about it: where it comes from, how it is signed, and whether it is a subtotal."""

    code: str
    label: str
    statement: str
    section: str
    sign: str
    #: Source accounts, for lines drawn straight from the trial balance. Empty for
    #: subtotals and for cash-flow lines, which are derived rather than posted.
    accounts: tuple[str, ...] = ()
    #: ``(line_code, coefficient)`` pairs. Present iff this line is a subtotal.
    subtotal_of: tuple[tuple[str, int], ...] | None = None
    #: ``False`` for lines a hand-prepared upload may legitimately omit.
    required: bool = True

    @property
    def is_subtotal(self) -> bool:
        return self.subtotal_of is not None


def _line(
    code: str,
    label: str,
    statement: str,
    section: str,
    sign: str,
    *,
    accounts: tuple[str, ...] = (),
    subtotal_of: tuple[tuple[str, int], ...] | None = None,
    required: bool = True,
) -> StatementLineDef:
    return StatementLineDef(code, label, statement, section, sign, accounts, subtotal_of, required)


