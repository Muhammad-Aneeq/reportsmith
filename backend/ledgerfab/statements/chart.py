def is_debit_positive(code: str) -> bool:
    return NATURAL_DEBIT[ACCOUNTS_BY_CODE[code].type]


def is_pnl_account(code: str) -> bool:
    return IS_PROFIT_AND_LOSS[ACCOUNTS_BY_CODE[code].type]


