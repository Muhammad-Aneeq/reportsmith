"""The extended chart of accounts, and the canonical statement-line vocabulary.

Two things live here, and the second is the more important one.

**The chart.** The vendored engine's 14 accounts describe a purchase cycle: cash, AR,
prepayments, AP, accruals, VAT, share capital, revenue and five expense accounts. That
is enough to reconcile a bank statement and nowhere near enough to draw a balance
sheet — there is no inventory, no fixed asset, no debt, no tax and no retained
earnings. ``STATEMENT_ACCOUNTS`` is that chart plus the accounts a set of statements
needs, with every base code preserved so a world generated by ``ledgerfab.generate``
and a statement set generated here speak the same language.

**The vocabulary.** ``STATEMENT_LINES`` is the one canonical list of line codes. The
emitter writes it, the CSV/XLSX template is generated from it, the parser validates
against it, and every formula addresses lines by it. Declaring it once — here, on the
engine side of the one-way import rule — is what stops the generate path and the
upload path from drifting apart (PLAN.md **D-004**).

Each line carries its own **sign convention** as data rather than as folklore, because
sign is exactly the thing that silently breaks a ratio:

* ``magnitude`` — always ≥ 0 as presented. Revenue, cost of sales, accumulated
  depreciation, accounts payable. A reader sees ``Cost of sales 1,240,000``, not
  ``-1,240,000``.
* ``signed`` — may be negative and means it. Subtotals (``net_income``), equity
  (``retained_earnings`` — negative equity is a case this project must handle, not
  avoid), and **every** cash-flow line, where inflow-positive makes ``cf_operating``
  a plain sum of its children.

Subtotals declare their components as ``(line_code, coefficient)`` pairs, so
``gross_profit = revenue − cogs`` and ``ppe_net = ppe_gross − accumulated_depreciation``
are data too. `derive.py` computes every subtotal from that declaration; nothing
hand-codes an addition.
"""

from __future__ import annotations

from dataclasses import dataclass

# --------------------------------------------------------------------- accounts --

#: Natural balance side per account type. Assets and expenses are debit-positive;
#: liabilities, equity and income are credit-positive. ``contra_asset`` (accumulated
#: depreciation) is an asset-section account that is credit-positive, which is why it
#: needs its own type rather than a special case somewhere downstream.
NATURAL_DEBIT: dict[str, bool] = {
    "asset": True,
    "contra_asset": False,
    "liability": False,
    "equity": False,
    "income": False,
    "expense": True,
}

#: ``True`` for accounts whose balance is a *flow* closed to retained earnings at each
#: period end, ``False`` for the *stock* accounts that carry forward.
IS_PROFIT_AND_LOSS: dict[str, bool] = {
    "asset": False,
    "contra_asset": False,
    "liability": False,
    "equity": False,
    "income": True,
    "expense": True,
}


@dataclass(frozen=True, slots=True)
class StatementAccount:
    code: str
    name: str
    type: str
    #: ``True`` for the two bank accounts. The cash-flow statement is built by asking
    #: which side of a journal entry was cash, so this flag is load-bearing.
    is_cash: bool = False
    #: Which cash-flow section a movement against this account belongs to, when it
    #: sits opposite cash in a journal entry. `derive.py` reads this instead of
    #: requiring every posting to be hand-tagged — a tag is a thing to get wrong.
    cf_section: str = "operating"
    #: `False` for accounts inherited from the base chart that this emitter models.
    added_by_extension: bool = True


